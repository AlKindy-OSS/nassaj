import type { TabsDisplayMode } from '../hooks/useUiPreferences';

/**
 * tabs-display-mode — الحلّ الوحيد لوضع عرض شريط التبويبات.
 *
 * ## المشكلة التي يحلّها (‏T-1319)
 *
 * كان نصّ التبويبة ملفوفاً بـ`hidden lg:inline` داخل `MainContentTabSwitcher`،
 * فالنصّ مخفيّ تحت 1024px **مهما كان التفضيل المخزَّن**. ونتيجة ذلك أنّ الوضع
 * `full` والوضع `compact` متطابقان بالبكسل تحت تلك العتبة (وعنصر `display:none`
 * لا يُسهم في `gap` الـflex أصلاً) — بينما الزرّ الدوّار ومربّع الإعدادات
 * السريعة يعرضان القيمة المخزَّنة، فيقولان «فرد (أيقونات + نصوص)» والشاشة
 * أيقونات عارية، وأوّل ضغطة (`full → compact`) تُنتج صفر تغيير مرئي. تحكّمٌ
 * يصف حالةً غير التي على الشاشة يُعلّم المستخدم ألّا يثق بالتحكّم.
 *
 * ## القاعدة
 *
 * العتبة تُوحَّد هنا ويقرأ مخرَجَها **كلُّ** مستهلك (الزرّ، المربّع، مبدّل
 * التبويبات، مؤشّر الاستهلاك) — فلا تبقى طبقة CSS تقرّر شيئاً بمعزل عن
 * النموذج. ولهذا استُبدل `hidden lg:inline` بشرطٍ على المخرَج: عتبتان
 * متنافستان على قرارٍ واحد هما أصل العطل، لا علاجه.
 *
 * ## لماذا لا قيمة `'auto'` مخزَّنة
 *
 * لأنّ الحلّ يُطبَّق على `'full'` الصريحة أيضاً (وهو ما تفرضه الحاجة: نصوص
 * تبويبات على هاتف بعرض 360px ليست تفضيلاً بل فيضان)، فيصير
 * `resolve('auto') ≡ resolve('full')` في كلّ بيئة ممكنة — أي أنّ القيمة
 * الخامسة لا تحمل معلومة واحدة زائدة، وثمنها ترحيلٌ على كتلة مُزامَنة وتوسيعُ
 * `ENUM_KEYS` وإعادةُ كتابة `reconcileTabsMode`. أُسقطت بمراجعة نقدية.
 *
 * ‏`minimal` و`hidden` مستقلّان عن البيئة: كلاهما نيّةٌ صريحة («أخفِ
 * التبويبات») لا تُنقض بعرض الشاشة، ويعبران أجهزة الحساب عمداً.
 */

/** عتبة `lg` في Tailwind (لا تجاوز لها في `tailwind.config.js`). */
export const TABS_TEXT_MIN_WIDTH = 1024;

/** الشاشة أضيق من `lg` — نفس حدّ `hidden lg:inline` الذي حلّت هذه الدالّة محلّه. */
export const NARROW_QUERY = `(max-width: ${TABS_TEXT_MIN_WIDTH - 0.02}px)`;

/**
 * مؤشّرٌ خشن = جهاز لمس. يلتقط الجهاز اللوحي أفقياً (آيباد إير 1180px، وبرو
 * 1366px) وهو ‏≥ `lg` فيفوته حدّ العرض وحده، ومع ذلك يريده المستخدم مضغوطاً.
 * ويترك حاسوباً بشاشة لمس على حاله لأنّ مؤشّره الأوّلي فأرة (`pointer: fine`).
 */
export const COARSE_POINTER_QUERY = '(pointer: coarse)';

export type TabsDisplayEnvironment = {
  /** الشاشة أضيق من `lg` أو المؤشّر الأوّلي خشن. */
  isNarrowOrCoarse: boolean;
};

/**
 * يحوّل الوضع المخزَّن إلى الوضع الذي يُعرض فعلاً.
 *
 * دالّة نقيّة بلا DOM ولا React، فتُختبَر جدولياً بلا تركيب أي مكوّن.
 */
export function resolveTabsMode(
  stored: TabsDisplayMode,
  env: TabsDisplayEnvironment,
): TabsDisplayMode {
  // نيّة صريحة لا تُنقض بالبيئة.
  if (stored === 'minimal' || stored === 'hidden') {
    return stored;
  }
  return env.isNarrowOrCoarse ? 'compact' : stored;
}
