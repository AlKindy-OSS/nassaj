/** الشرطة التي تحلّ محلّ رقم لا نملكه — ولا تحلّ محلّها صفر أبداً. */
export const RESOURCE_DASH = '—';

/**
 * ميغابايت إلى نصّ مقروء: دون 1024 بالميغا، وفوقها بالغيغا برقم عشري واحد.
 * الرقم غير الصالح يصير شرطة لا صفراً — الصفر يُقرأ «لا يستهلك شيئاً» وهو
 * ادّعاء، والشرطة اعتراف.
 */
export function formatMb(mb: number): string {
  // الصفر شرطةٌ لا رقم: «تستهلك 0MB» ادّعاءٌ لا نملكه، وهو ما كان يظهر فعلاً
  // حين تفشل كل قياسات الشجرة (مراجعة نقدية 2026-07-31).
  if (!Number.isFinite(mb) || mb <= 0) return RESOURCE_DASH;
  if (mb < 1024) return `${Math.round(mb)}MB`;
  return `${(mb / 1024).toFixed(1)}GB`;
}
