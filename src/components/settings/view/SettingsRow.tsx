import type { ReactNode } from 'react';
import { cn } from '../../../lib/utils';

/**
 * صفّ إعداد — **عمودان متجاوران، بلا خطّ**.
 *
 * **العلّة التي يعالجها، مقيسةً لا موصوفة.** كان الصفّ `justify-between` على عرض
 * 620px، فاللصيقة في طرف وتحكّمها في الطرف الآخر و**359px فراغ ميّت بينهما —
 * 58% من الصفّ**. على تلك المسافة لا تربط المجاورةُ شيئاً، فلم يبقَ ما يقول «هذه
 * اللصيقة لهذا التحكّم» إلا خطٌّ أفقي. ولمّا صار الخطّ الرابط الوحيد وجب رسمه عند
 * كل حدّ — فامتلأت الشاشة خطوطاً بلا معنى («كأنها دفتر»).
 *
 * فالخطوط كانت **عَرَضاً لا مرضاً**. حذفُها وحده كان سيُنتج الشكوى المضادّة
 * («عايمة على بعض»)، وإبقاؤها يُنتج الدفتر. الحلّ الذي يُسقط الشكويين معاً هو
 * إلغاء سبب وجودها: عمود لصيقة محدود العرض، وتحكّمٌ يبدأ **بعده مباشرة** بفجوة
 * 24px — على هذه المسافة تربط المجاورةُ وحدها، فلا يبقى للخطّ عمل.
 *
 * الفراغ الفائض يذهب إلى **نهاية** الصفّ لا إلى وسطه: فراغٌ عند الحافة راحةٌ
 * للعين، وفراغٌ بين شيئين مترابطين قطعٌ للرابط.
 *
 * **تصحيح 2026-08-03 (شكوى المالك الثالثة).** التشخيص أعلاه كان صحيحاً والعلاج
 * خاطئاً: عمودُ لصيقةٍ بسقف `15rem` وتحكّمٌ يليه **بمحاذاة البداية** يُنهي الصفّ
 * عند ~60% من العرض، فيبقى ثلث الشاشة أبيض في كل صفّ — والصفحة تُقرأ خاوية.
 * قِيس على لقطة تبويب المستخدمين: محتوى ينتهي عند 1280px في حاويةٍ عرضها 1690.
 *
 * ولمّا كان الفراغ الميّت الأصلي (359px) عَرَضاً لغياب ما يربط اللصيقةَ بتحكّمها،
 * فقد زال سببُه من جهةٍ أخرى: صار لكل قسم **أيقونةٌ وعنوانٌ كبير** يحدّانه
 * (‏ADR-094)، فالصفّ لم يعد يسبح وحده. فالعلاج الصحيح ليس ضغطَ المحتوى في عمود،
 * بل ما يفعله الأصل وكل تطبيق إعدادات: **اللصيقة عند حافة، والتحكّم عند الحافة
 * المقابلة، والمساحة بينهما يملؤها التحكّم إن كان يقبل الامتداد** (حقلٌ أو
 * منتقٍ عبر `stacked`)، فلا يبقى فراغ في الوسط ولا عند الطرف.
 */
type SettingsRowProps = {
  label: ReactNode;
  description?: ReactNode;
  children?: ReactNode;
  className?: string;
  /** تحكّم يحتاج العرض كاملاً (حقل نصّي، محرّر): ينزل تحت اللصيقة. */
  stacked?: boolean;
};

export default function SettingsRow({
  label,
  description,
  children,
  className,
  stacked,
}: SettingsRowProps) {
  const heading = (
    <div className="min-w-0">
      <div className="text-[15px] font-medium leading-relaxed text-foreground">{label}</div>
      {description && (
        <div className="mt-0.5 text-[13px] leading-relaxed text-muted-foreground">
          {description}
        </div>
      )}
    </div>
  );

  if (stacked) {
    // التحكّم ينزل تحت اللصيقة **بالعرض كاملاً**. الغلاف وحده `w-full`؛ لا
    // تُفرَض على الابن، وإلا دفع حقلٌ `w-full` زرَّه المجاور إلى سطر جديد —
    // والأصل يضع الزرّ **بجانب** الحقل لا تحته.
    return (
      <div className={cn('w-full space-y-2 py-2.5', className)}>
        {heading}
        {children && <div className="w-full">{children}</div>}
      </div>
    );
  }

  return (
    <div
      className={cn(
        // طرفٌ وطرف: اللصيقة عند حافة الكتابة، والتحكّم عند الحافة المقابلة.
        // على الشاشات الضيّقة ينهار الصفّ إلى عمود.
        'flex flex-col gap-1.5 py-2.5',
        'sm:flex-row sm:items-center sm:justify-between sm:gap-6',
        className,
      )}
    >
      {heading}
      {children && <div className="min-w-0 shrink-0 sm:text-end">{children}</div>}
    </div>
  );
}
