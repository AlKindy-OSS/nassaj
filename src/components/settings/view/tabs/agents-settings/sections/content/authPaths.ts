import { vendorForSlot } from '../../../../../../../../shared/vendors';

/**
 * طريقا الاعتماد — تمييزٌ مشتقٌّ من الكتالوج لا مكتوبٌ بيد (شكوى المالك
 * 2026-08-03).
 *
 * قال المالك: «الاعتماد بأحد طريقتين: إمّا **اشتراك** يُفعَّل بـOAuth، أو **مفتاح
 * API**». وكان تبويب الحساب يعرض أربعة أقسامٍ متتابعة — حالة الاتصال، إعادة
 * المصادقة، مشاركة الاعتماد، اعتماد المورّد — لا يقول شيءٌ منها إنّ الأوّلين
 * طريقٌ والأخير طريقٌ **بديلٌ عنه**. فالقارئ يرى أربع خطواتٍ متتابعة حيث الواقع
 * خيارٌ من اثنين.
 *
 * و«اثنان» ليست صفةَ كل وكيل: `credential` في سجلّ المورّدين يقولها حرفياً —
 * `both` وحدها تعني «تسجيل دخول الوكيل نفسه، **و**مفتاح API بديلاً عنه»
 * (‏Anthropic وOpenAI وMoonshot اليوم). و`api_key` تعني طريقاً واحداً لا خيار
 * فيه (DeepSeek وZ.AI)، فلا يُطوى منها شيء ولا يُوعَد بطريقٍ ثانٍ لا وجود له.
 *
 * ولهذا لا خريطةَ أسماءٍ هنا: أيّ وكيلٍ يصير مورّدُه `both` غداً يرث السلوك بلا
 * تعديل، وأيّ وكيل يفقده يفقده — وهي عين القاعدة التي كُتب لأجلها ADR-085.
 */
export function hasDualAuthPaths(agent: string): boolean {
  return vendorForSlot(agent)?.credential === 'both';
}
