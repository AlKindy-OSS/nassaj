/**
 * سطح «المرجعيّات» — الأنواع المشتركة بين المواد الأربع.
 *
 * القاعدة الحاكمة (‏`docs/design/coordination-levels-ux-2026-08-07.md` §4.2):
 * **شكلٌ واحد ونِسَبٌ مختلفة**. أربع موادّ مختلفةِ الطبائع — ملفُّ نصٍّ طويل،
 * وملفّاتٌ صغيرةٌ كثيرة، وبطاقاتٌ بحقول، ومجلّدات — تتشارك قالباً واحداً:
 * «قائمةٌ مجمَّعةٌ بالنطاق ← رأسٌ + حقولٌ + جسمُ نصّ»، ويختلف بينها **وزنُ الحقول
 * إلى الجسم** لا الشكل. فلا يُبنى أربعة سطوح ولا تُصمَّم حالاتُ الفراغ والخطأ
 * أربع مرّات.
 */

/**
 * **مَن يتأثّر بتعديل هذا الملف** — لا أين يسكن (§4.3-3).
 *
 * ‏`unknown` ليست تهرّباً: الخادم لا يصرّح بالنطاق لكل قناة (‏`linkScope` يبقى
 * ‏`null` على القنوات غير القابلة للربط)، و«خاصٌّ بي» المكتوبة عن ملفٍّ عامّ هي
 * **الفشل الوحيد الذي يوقف الإطلاق** (§9، م٤). فحين لا يصرّح الخادم نقول ذلك
 * صراحةً — الغيابُ أصدقُ من ادّعاء.
 */
export type ReferenceScope = 'global' | 'mine' | 'project' | 'unknown' | 'no-channel';

/** مرشِّح النطاق — **واحدٌ ثابت فوق المواد الأربع** لا وسمٌ على كل مادة (§4.2). */
export type ReferenceScopeFilter = 'all' | 'global' | 'mine' | 'project';

/** المواد الأربع التي يتشاركن سؤالاً واحداً: «ماذا يصل الوكيل قبل أن يبدأ؟» */
export type ReferenceMaterial = 'instructions' | 'memory' | 'agents' | 'skills';

/**
 * ترتيب المجموعات في القائمة: الأعمّ أثراً أوّلاً، و**ما لا ملفَّ له آخراً**.
 *
 * ‏`no-channel` ليست نطاقاً بل جوابٌ عن سؤال النطاق: «لا أحد يتأثّر لأنه لا ملفّ».
 * وهي تُعرض ولا تُخفى بقاعدة T-1232 — محرّكٌ لا تصله تعليمات **يجب** أن يُقال ذلك
 * عنه، وإلّا فُسِّر تجاهلُه عطلاً (‏§4.4: «‏Hermes — لا قناة تعليمات لهذا المحرّك»).
 */
export const REFERENCE_SCOPE_ORDER: readonly ReferenceScope[] = Object.freeze([
  'global',
  'project',
  'mine',
  'unknown',
  'no-channel',
]);

export type ReferenceField = {
  key: string;
  label: string;
  value: string;
  /** نصّ تقني (مسار/أمر): عزلٌ ثنائي الاتجاه + أحادي المسافة. */
  technical?: boolean;
  /**
   * قيمةٌ جملةٌ لا كلمة ⇒ تنزل تحت لصيقتها.
   *
   * **مقيسٌ على لقطة، لا احتياط.** ‏`SettingsRow` غيرُ المكدَّس يضع التحكّم في
   * غلافٍ `shrink-0`، فقيمةٌ من جملةٍ كاملة داخل عمودِ تفاصيلٍ عرضُه ~400px
   * **تركب لصيقتَها حرفياً** — رُئي ذلك على «الآلية» و«Description» في أول
   * لقطة. والتكديس يحلّها بلا مسٍّ ببدائيةٍ يستهلكها عشرون موضعاً.
   */
  wide?: boolean;
  /** سطرُ سببٍ تحت اللصيقة. */
  description?: string;
};

export type ReferenceItem = {
  id: string;
  /** ما يُقرأ في القائمة. */
  title: string;
  /** العنوان نصٌّ تقني (مسار، أمر) — يُعزَل `dir="ltr"`. */
  titleTechnical?: boolean;
  /** سطرٌ واحد تحت العنوان في القائمة. */
  summary?: string;
  scope: ReferenceScope;
  /** اسم المشروع — إلزاميٌّ حين `scope === 'project'` (§4.3-3: «المشروع» بلا اسمٍ مرفوضة). */
  projectName?: string;
  /** شارةٌ إضافية في صفّ القائمة: المحرّك الذي تخصّه المادة. */
  tag?: string;
  fields: ReferenceField[];
  /**
   * جسمُ النصّ. `null` = **لا قناة قراءةٍ على هذا الخادم اليوم** — تُعرَض حينها
   * جملةٌ صادقة ومسارُ الملف، لا هيكلٌ عظميٌّ دائم ولا محتوىً مُلفَّق.
   */
  body: string | null;
  /** مسار الملف — يُقال حين يغيب الجسم فيعرف القارئ أين ينظر بنفسه (§6). */
  bodyPath: string | null;
  /**
   * يحلّ محلّ جملة «المحتوى غير متاح بعد» حين يكون سببُ الغياب **غيرَ ذلك**.
   *
   * الفرق ليس تجميلاً: «لا قناة قراءةٍ لملفٍّ موجود» و«لا ملفَّ أصلاً» جوابان
   * مختلفان يترتّب عليهما فعلان مختلفان — الأوّل ينتظر بناءَ قناة، والثاني
   * ينتظر قراراً بربط المحرّك أو لا شيء. وجملةٌ واحدة لسببين تُقرأ حجباً (§5.3).
   */
  contentNote?: string;
  /** صلاحية التحرير كما صرّح بها الخادم؛ لا تُستنتج من دورٍ مخزّن في العميل. */
  canEdit?: boolean;
  canCreateSibling?: boolean;
  affectedScope?: 'all_members' | 'current_user' | 'project' | 'none' | 'unknown';
};
