import type { ReactNode } from 'react';

import { cn } from '../../../lib/utils';

/**
 * قائمة صفوف إعدادات — **بلا خطوط ولا حدود افتراضياً**.
 *
 * كانت هذه البدائية ترسم `border-y` حول القائمة و`divide-y` بين صفوفها. وذلك
 * أنتج ما وصفه المالك بـ«كمية الخطوط بالعرض، مالها معنى» — وهو وصفٌ دقيق: على
 * شاشة واحدة ستّة خطوط أفقية مِلءَ العرض بنفس السُّمك واللون، ثلاثة تفصل صفوفاً
 * وثلاثة تفصل أقساماً، فلا يميّز الخطُّ مستوىً من مستوى ولا يقول شيئاً.
 *
 * حُذفت كلها لأن سبب وجودها زال: الخطّ كان يربط لصيقةً بتحكّمٍ يبعد عنها 359px
 * (‏`SettingsRow`)، فلمّا صارا متجاورين لم يبقَ له عمل. والفصل الآن بالإيقاع
 * الرأسي وحده — وهو ما يفعله الأصل نفسه (‏upstream claudecodeui): صفوفٌ متتابعة
 * بفراغ، والحدّ محجوزٌ لصندوق النبرة وحده.
 *
 * ── استثناء `divided`، بحدٍّ مكتوب (قرار المالك 2026-08-03) ────────────────────
 *
 * «صفحة المستخدمين ممكن تُستخدم فيها خطوط الجدول، **لكن لا تُعمَّم كنمط على كل ما
 * يشبهها**». فالخاصيّة اختيارية والافتراضي `false` — لأن تعديل هذه البدائية نفسها
 * لترسم خطوطاً هو عين التعميم الممنوع: يستهلكها عشرون موضعاً فينقلب الاستثناء
 * قاعدةً بسطرٍ واحد.
 *
 * **متى يُسمح الخطّ:** قائمةٌ **متجانسة الصفوف يقارن القارئ صفوفها ببعضها** — كل
 * صفّ فيها نفس بنية الحقول (اسم، دور، أفعال) والعينُ تمسح عموداً لا صفّاً، فالخطّ
 * يقول «هذا الصفّ انتهى وذاك بدأ» وهي معلومة يحتاجها المسح العمودي. جدول الأعضاء
 * في تبويب المستخدمين هو الحالة الوحيدة المُصرَّح بها اليوم.
 *
 * **متى يُمنع:** كل ما عداه. صفوفُ إعداداتٍ مختلفة الطبيعة (مفتاح، حقل، منتقٍ)
 * لا يقارن القارئ بينها فلا يحمل الخطّ فيها معلومة — وستّة خطوط بلا معلومة على
 * شاشة واحدة هي الشكوى التي أسقطت الخطوط أصلاً (§0 من الـBrief). وكذلك القوائم
 * القصيرة (الدعوات المعلّقة) وقوائم الكيانات في التبويبات الأخرى: تسويغُ «هي
 * أيضاً قائمة» هو التعميم بعينه.
 *
 * الحارس: `settingsSurfaceLanguage.test.ts` — يسقط إن ظهر `divided` خارج
 * `UsersSettingsTab.tsx` أو ظهر `divide-y` مكتوباً بيدٍ في ملفٍ جديد.
 */
type SettingsGroupProps = {
  children: ReactNode;
  className?: string;
  /** عنصر الغلاف. `ul` حين تكون الصفوف `li` (دلالةٌ لقارئ الشاشة لا زخرفة). */
  as?: 'div' | 'ul';
  /** فواصل شعرية بين الصفوف. **لا تُرفع إلا على قائمةٍ متجانسة** — انظر أعلاه. */
  divided?: boolean;
};

export default function SettingsGroup({
  children,
  className,
  as: Tag = 'div',
  divided = false,
}: SettingsGroupProps) {
  return (
    <Tag
      className={cn(
        // مع الخطّ لا فجوة: حشو `SettingsRow` (‏`py-2.5`) يصير هو المسافة، والخطّ
        // في منتصفها. الفجوة فوقه تُنتج خطّاً يسبح بعيداً عن صفّيه معاً.
        divided ? 'divide-y divide-border' : 'space-y-1',
        className,
      )}
    >
      {children}
    </Tag>
  );
}
