/**
 * B-1668 item 3 (Claude): the title is a rename, else Claude's ai-title, else
 * the FIRST real prompt cleaned of injected blocks — never the raw last-prompt.
 * Record shapes follow a live transcript (queue-operation lines, then a user
 * record whose string content carries the server's image list).
 */
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';

import { closeConnection, initializeDatabase, sessionsDb } from '@/modules/database/index.js';
import { ClaudeSessionSynchronizer } from '@/modules/providers/list/claude/claude-session-synchronizer.provider.js';

const SESSION_ID = '11111111-2222-3333-4444-666666666666';
const CWD = '/workspace/title-project';
const IMAGES = '\n\n[Images provided at the following paths:]\n1. /home/user/.nassaj/chat-images/a.png\n2. /home/user/.nassaj/chat-images/b.png';

const base = { sessionId: SESSION_ID, cwd: CWD };
const queue = { ...base, type: 'queue-operation', operation: 'enqueue' };
const user = (content: unknown, extra: Record<string, unknown> = {}) =>
  ({ ...base, type: 'user', message: { role: 'user', content }, ...extra });

async function withTranscript(
  records: unknown[],
  runTest: (sync: ClaudeSessionSynchronizer) => Promise<void>,
): Promise<void> {
  const previousDatabasePath = process.env.DATABASE_PATH;
  const tempHome = await mkdtemp(path.join(os.tmpdir(), 'claude-title-'));
  const original = os.homedir;
  (os as { homedir: () => string }).homedir = () => tempHome;
  closeConnection();
  process.env.DATABASE_PATH = path.join(tempHome, 'auth.db');
  await initializeDatabase();
  try {
    const projectDir = path.join(tempHome, '.claude', 'projects', '-workspace-title-project');
    await mkdir(projectDir, { recursive: true });
    await writeFile(path.join(projectDir, `${SESSION_ID}.jsonl`), `${records.map((r) => JSON.stringify(r)).join('\n')}\n`);
    await runTest(new ClaudeSessionSynchronizer());
  } finally {
    (os as { homedir: () => string }).homedir = original;
    closeConnection();
    if (previousDatabasePath === undefined) delete process.env.DATABASE_PATH;
    else process.env.DATABASE_PATH = previousDatabasePath;
    await rm(tempHome, { recursive: true, force: true });
  }
}

const storedName = () => sessionsDb.getSessionById(SESSION_ID)?.custom_name;

test('the first real prompt names the session, without the image list, never the last prompt', async () => {
  await withTranscript([
    queue,
    queue,
    user('<command-name>/clear</command-name>'),
    user([{ type: 'tool_result', tool_use_id: 't1', content: 'ok' }]),
    user('Caveat: The messages below were generated by the user while running local commands.', { isMeta: true }),
    user(`فين الحساب اللي مسجّل بيه${IMAGES}`),
    user('second prompt'),
    { ...base, type: 'last-prompt', lastPrompt: `LAST PROMPT${IMAGES}` },
  ], async (sync) => {
    await sync.synchronize();
    assert.equal(storedName(), 'فين الحساب اللي مسجّل بيه');
  });
});

test('an image-only first prompt is skipped for the next real one', async () => {
  await withTranscript([queue, user(IMAGES.trim()), user('the real question')], async (sync) => {
    await sync.synchronize();
    assert.equal(storedName(), 'the real question');
  });
});

test('ai-title beats the first prompt, and a rename (custom-title) beats ai-title', async () => {
  await withTranscript([
    user('first prompt'),
    { ...base, type: 'ai-title', aiTitle: 'Claude title' },
  ], async (sync) => {
    await sync.synchronize();
    assert.equal(storedName(), 'Claude title');
  });

  await withTranscript([
    user('first prompt'),
    { ...base, type: 'custom-title', customTitle: 'Renamed' },
    { ...base, type: 'ai-title', aiTitle: 'Claude title' },
  ], async (sync) => {
    await sync.synchronize();
    assert.equal(storedName(), 'Renamed');
  });
});

test('a stored name is kept; a stored placeholder or empty-after-cleaning name is re-derived', async () => {
  await withTranscript([user('first prompt')], async (sync) => {
    sessionsDb.createSession(SESSION_ID, 'claude', CWD, 'kept name');
    await sync.synchronize();
    assert.equal(storedName(), 'kept name');

    sessionsDb.updateSessionCustomName(SESSION_ID, 'Untitled Claude Session');
    await sync.synchronize();
    assert.equal(storedName(), 'first prompt');

    sessionsDb.updateSessionCustomName(SESSION_ID, '<system-reminder>only a block</system-reminder>');
    await sync.synchronize();
    assert.equal(storedName(), 'first prompt');
  });
});

test('an oversized first record is skipped without parsing it', async () => {
  const huge = user(`${'x'.repeat(200 * 1024)}`);
  await withTranscript([huge, user('after the huge one')], async (sync) => {
    await sync.synchronize();
    assert.equal(storedName(), 'after the huge one');
  });
});
