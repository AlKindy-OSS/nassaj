/**
 * vendor-key-migration.runtime — ADR-200 S5: the production wiring of the
 * vendor-key migration (harness file locations, members, audit, clock). Kept
 * apart from the service so its tests inject plain fakes.
 */

// Namespace import on purpose (same reason as harness-link-mode.runtime): many
// test files mock the database barrel with a partial export set.
import * as database from '@/modules/database/index.js';
import {
  PROJECTION_FINGERPRINT_KEY_VERSION,
  isServerKeyFreshOverExistingStore,
  isUnifiedVendorKeysEnabled,
  projectionFingerprint,
} from '@/services/isolation/provider-secrets-store.js';
import { isProviderIsolated } from '@/services/provider-sharing.js';

import type { HarnessFileLocation, ProjectionHarness } from './vendor-key-migration.inventory.js';
import { createVendorKeyMigrationService } from './vendor-key-migration.service.js';
import { listSweepMemberIds, ownHarnessFilePath } from './vendor-key-sweep-members.js';

const HARNESSES: readonly ProjectionHarness[] = ['claude', 'codex', 'opencode'];

/**
 * The member's OWN credential file per harness, at the path the writers use
 * (`honorGrants: false`, B-1251), computed without provisioning (B-1575). A
 * shared harness is `shared` and never inventoried: its files are the
 * operator's, not this member's.
 */
function locateHarnessFiles(userId: string | number): HarnessFileLocation[] {
  return HARNESSES.map((harness) => (isProviderIsolated(harness)
    ? { harness, scope: 'own', path: ownHarnessFilePath(userId, harness) }
    : { harness, scope: 'shared' }));
}

function toAuditUserId(userId: string | number): number | undefined {
  const id = Number(userId);
  return Number.isInteger(id) && id > 0 ? id : undefined;
}

export const vendorKeyMigrationService = createVendorKeyMigrationService({
  isEnabled: () => isUnifiedVendorKeysEnabled(),
  locateHarnessFiles,
  fingerprint: (value, keyVersion) => projectionFingerprint(value, keyVersion),
  keyVersion: PROJECTION_FINGERPRINT_KEY_VERSION,
  listMemberIds: listSweepMemberIds,
  audit: (userId, action, metadata) => {
    database.auditLogDb?.record(action, { userId: toAuditUserId(userId), metadata });
  },
  now: () => new Date(),
  // Loaded at call time: provider-credentials.service reaches this module back through the backup guard.
  withHarnessLock: async (userId, harness, work) => {
    const { providerCredentialsService } = await import('./provider-credentials.service.js');
    return providerCredentialsService.withCredentialFileLock(userId, harness, work);
  },
});

/** Daily: the purge is due 30 days after verification, whether or not the server restarts. */
const SWEEP_INTERVAL_MS = 24 * 60 * 60 * 1000;

/** ADR-200 S6: the fan-out retry sweep (failed, stale, tombstones); loaded only in-flag. */
async function runFanoutSweep(): Promise<void> {
  const { vendorKeyFanoutService } = await import('./vendor-key-fanout.runtime.js');
  await vendorKeyFanoutService.sweepAll();
}

/**
 * B-1575: a server key generated by this process while older keys.json files
 * exist means those files were sealed under another key; the sweep then
 * adopts and backs up nothing. A key that cannot be loaded skips it too.
 */
export function vendorKeySweepBlockedByFreshKey(): boolean {
  try {
    return isServerKeyFreshOverExistingStore();
  } catch {
    return true;
  }
}

/**
 * Runs the migration for every member at server start, then daily, when the
 * flag is on (§3: it re-runs idempotently each time the flag is turned on),
 * followed by the S6 fan-out retry sweep: `failed` and `stale` projections are
 * retried and tombstones drained. A no-op with the flag off, and skipped with a
 * warning while the server key is fresh over an existing store. Never throws.
 */
export function startVendorKeyMigrationSweep(): void {
  if (!isUnifiedVendorKeysEnabled()) return;
  const sweep = () => {
    if (vendorKeySweepBlockedByFreshKey()) {
      console.warn('[vendor-key-migration] sweep skipped: the server key is new or unreadable while stored keys exist');
      return;
    }
    vendorKeyMigrationService.runAll().then(runFanoutSweep).catch(() => {
      console.error('[vendor-key-migration] sweep failed');
    });
  };
  sweep();
  setInterval(sweep, SWEEP_INTERVAL_MS).unref();
}
