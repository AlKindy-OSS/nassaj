// ---- the plugin under dsh-tools-host, wired to a broker over fd 3 -------------------
interface HostRun { rows: Row[]; witness: string[]; signal: string | null; incidents: Row[]; broker: Row; }
async function runHost(script: Row, brokerDeps: Row = {}): Promise<HostRun> {
  const dir = fs.mkdtempSync(path.join(sandbox, 'host-'));
  const scriptFile = path.join(dir, 'script.json');
  fs.writeFileSync(scriptFile, JSON.stringify(script));
  // Resolve every S2 export BEFORE the child exists, so a red run leaves no process behind.
  const createBroker = need(BROKER_MODULE, 'createParityBroker');
  assert.ok(fs.existsSync(PLUGIN), `${path.relative(appRoot, PLUGIN)} does not exist`);
  const engine = brokerDeps.engine ?? await engineFor('default');
  const child = spawn(process.execPath, [HOST, PLUGIN, scriptFile, dir], { stdio: ['ignore', 'pipe', 'pipe', 'pipe'] });
  const incidents: Row[] = [];
  const broker = createBroker({
    engine,
    kill: () => child.kill('SIGKILL'), onIncident: (incident: Row) => incidents.push(incident),
    askMember: brokerDeps.askMember ?? (async () => 'reject'),
  });
  broker.attach(child.stdio[3]);
  let stdout = '';
  child.stdout!.on('data', (chunk) => { stdout += chunk; });
  const signal = await Promise.race([
    new Promise<string | null>((resolve) => child.once('exit', (_code, sig) => resolve(sig))),
    new Promise<string | null>((_, reject) => setTimeout(() => { child.kill('SIGKILL'); reject(new Error('host timed out')); },
      DEADLINE_MS)),
  ]);
  const log = path.join(dir, 'executions.log');
  return {
    rows: stdout.trim().split('\n').filter(Boolean).map((line) => JSON.parse(line)),
    witness: fs.existsSync(log) ? fs.readFileSync(log, 'utf8').trim().split('\n').filter(Boolean) : [],
    signal, incidents, broker,
  };
}
