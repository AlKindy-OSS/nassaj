/**
 * opencode-local-tier-material — the pure material of the compact local instruction
 * tier (ADR-LOCAL-INSTR-TIER-001, S4). A local-model OpenCode turn runs under its own
 * config dir (~/.nassaj-users/<id>/.config-local/opencode) holding:
 *  - AGENTS.md: a verified copy of ~/.claude/AGENTS.local.md (`tier=local32` REV);
 *  - opencode.json: the usual provider/limit material plus a `permission.task`
 *    allow-list (LOCAL_TASK_AGENTS), and NO webfetch rule (qa C4);
 *  - agent/: GENERATED copies of the allowed cards, by default without their
 *    `model:` pin so subagents inherit the local session model (qa C2).
 * Nothing here falls back to the full instructions file.
 */

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

/** The compact tier a local turn runs (nassaj-core build-agents TIERS). */
export const LOCAL_INSTRUCTION_TIER = 'local32';

/** Per-user XDG_CONFIG_HOME of local turns, beside the ordinary `.config`. */
export const OPENCODE_LOCAL_CONFIG_SUBDIR = '.config-local';

/** The slim source under ~/.claude, generated by nassaj-core build-agents. */
export const LOCAL_INSTRUCTIONS_FILENAME = 'AGENTS.local.md';

/**
 * The only agents a local coordinator may hand work to; every other one is denied.
 * Default pending the owner's confirmation (qa T1) — change it here only.
 */
export const LOCAL_TASK_AGENTS = Object.freeze(['researcher', 'backend-dev', 'devops', 'scribe', 'qa-critic']);

/**
 * true: generated cards drop `model:`, so subagents run on the local session model.
 * false: cards keep their cloud pins. Default pending the owner's decision (qa C2).
 */
export const LOCAL_SUBAGENTS_INHERIT_SESSION_MODEL = true;

/** Refusal code of a local turn whose slim instructions are missing or invalid. */
export const LOCAL_INSTRUCTIONS_UNAVAILABLE = 'local_instructions_unavailable';

/** User-facing refusal (Arabic, with an English gloss for operators). */
export const LOCAL_INSTRUCTIONS_UNAVAILABLE_MESSAGE =
  'لم يبدأ التشغيل: تعليمات نسّاج المختصرة للنماذج المحلية غير متاحة أو غير صالحة على هذا الخادم. '
  + 'حدّث نسّاج-كور على الخادم ثم أعد المحاولة. (Local-model instructions are missing or invalid.)';

/**
 * The header line every local32 file carries. The tier tag sits outside the REV hash,
 * so the header is what tells a genuine slim file from a full file with a tag
 * appended (qa round 1); a full file must never carry it.
 */
export const LOCAL_TIER_HEADER = '# AGENTS.local.md — Nassaj compact instructions (tier local32)';

const REV_PREFIX = 'NASSAJ-INSTR-REV: ';
const REV_TIER_SEP = ' tier=';
const REV_LEN = 12;
const CARD_MODE = 0o444;
const DIR_MODE = 0o700;

/** Refusal code of a local turn whose generated agent cards cannot be built. */
export const LOCAL_AGENT_CARDS_UNAVAILABLE = 'local_agent_cards_unavailable';

/** User-facing refusal for missing agent cards (Arabic, with an English gloss). */
export const LOCAL_AGENT_CARDS_UNAVAILABLE_MESSAGE =
  'لم يبدأ التشغيل: بطاقات الوكلاء الخاصة بالنماذج المحلية غير متاحة على هذا الخادم. '
  + 'حدّث نسّاج-كور على الخادم ثم أعد المحاولة. (Local-model agent cards are unavailable.)';

/** Thrown when an allowed agent card is missing; the launcher refuses the turn. */
export class LocalAgentCardsUnavailableError extends Error {
  /** @param {string} reason operator triage detail (never shown to the user) */
  constructor(reason) {
    super(LOCAL_AGENT_CARDS_UNAVAILABLE_MESSAGE);
    this.name = 'LocalAgentCardsUnavailableError';
    this.code = LOCAL_AGENT_CARDS_UNAVAILABLE;
    this.reason = reason;
  }
}

/** Thrown when the local tier cannot be set up; the launcher refuses the turn. */
export class LocalInstructionsUnavailableError extends Error {
  /** @param {string} reason operator triage detail (never shown to the user) */
  constructor(reason) {
    super(LOCAL_INSTRUCTIONS_UNAVAILABLE_MESSAGE);
    this.name = 'LocalInstructionsUnavailableError';
    this.code = LOCAL_INSTRUCTIONS_UNAVAILABLE;
    this.reason = reason;
  }
}

/**
 * Port of nassaj-core build-agents verify_rev (qa I6): the last line is a REV line
 * whose digest is the sha256 of everything above it, and its tier tag is exactly
 * `tier` (null = the full file, which carries no tag). The tag is outside the hash,
 * so the local tier also requires LOCAL_TIER_HEADER and the full file must lack it.
 * @param {string} content
 * @param {string|null} tier
 * @returns {string|null} null when valid, otherwise what is wrong
 */
export function verifyInstructionRev(content, tier) {
  if (!content.endsWith('\n')) return 'instructions must end with a newline after the REV line';
  const trimmed = content.slice(0, -1);
  const cut = trimmed.lastIndexOf('\n');
  const body = trimmed.slice(0, cut + 1);
  const last = trimmed.slice(cut + 1);
  if (!last.startsWith(REV_PREFIX)) return 'REV line missing or not the last line';
  if (body.includes(REV_PREFIX.trim())) return 'REV marker appears above the last line';
  const found = last.includes(REV_TIER_SEP) ? last.slice(last.indexOf(REV_TIER_SEP) + REV_TIER_SEP.length) : null;
  if (found !== tier) return `REV tier tag mismatch: found ${found ?? 'none'}, expected ${tier ?? 'none'}`;
  const digest = crypto.createHash('sha256').update(body, 'utf8').digest('hex').slice(0, REV_LEN);
  const expected = `${REV_PREFIX}${digest}${tier ? `${REV_TIER_SEP}${tier}` : ''}`;
  if (last !== expected) return 'REV mismatch: body does not match its REV line';
  const hasHeader = body.split('\n').includes(LOCAL_TIER_HEADER);
  if (tier === LOCAL_INSTRUCTION_TIER && !hasHeader) return 'local tier header line missing';
  if (tier === null && hasHeader) return 'full file carries the local tier header';
  return null;
}

/**
 * The REV line of an instruction file, parsed exactly as verifyInstructionRev does
 * (the last line before the single trailing newline), or null when there is none.
 * @param {string} content
 * @returns {string|null}
 */
export function instructionRevLine(content) {
  const trimmed = content.endsWith('\n') ? content.slice(0, -1) : content;
  const last = trimmed.slice(trimmed.lastIndexOf('\n') + 1);
  return last.startsWith(REV_PREFIX) ? last : null;
}

/**
 * I6 for the FULL slot: true when the file carries a tier tag on its REV line or the
 * local32 header anywhere — a compact file where the full one belongs.
 * @param {string} content
 */
export function carriesCompactTierMarks(content) {
  return Boolean(instructionRevLine(content)?.includes(REV_TIER_SEP))
    || content.split('\n').includes(LOCAL_TIER_HEADER);
}

/** @returns {{ task: Record<string, 'allow'|'deny'> }} the local permission block */
export function localTaskPermission() {
  return { task: { '*': 'deny', ...Object.fromEntries(LOCAL_TASK_AGENTS.map((agent) => [agent, 'allow'])) } };
}

/**
 * A generated card: the source card without its frontmatter `model:` line (C2).
 * @param {string} source
 * @param {{ inheritSessionModel?: boolean }} [options]
 */
export function localAgentCardContent(source, options = {}) {
  const inherit = options.inheritSessionModel ?? LOCAL_SUBAGENTS_INHERIT_SESSION_MODEL;
  if (!inherit || !source.startsWith('---\n')) return source;
  const end = source.indexOf('\n---', 4);
  if (end < 0) return source;
  const front = source.slice(0, end).split('\n').filter((line) => !/^model:/u.test(line)).join('\n');
  return front + source.slice(end);
}

/** Replaces a symlink or non-directory at `dir` with a real private directory. */
function ensureRealAgentDir(dir) {
  try {
    const stat = fs.lstatSync(dir);
    if (stat.isSymbolicLink() || !stat.isDirectory()) fs.rmSync(dir, { force: true });
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
  }
  fs.mkdirSync(dir, { recursive: true, mode: DIR_MODE });
  fs.chmodSync(dir, DIR_MODE);
}

/** Atomically writes a 0444 file unless it already holds exactly `content`. */
function writeReadOnly(file, content) {
  try {
    const stat = fs.lstatSync(file);
    if (stat.isFile() && !stat.isSymbolicLink() && fs.readFileSync(file, 'utf8') === content) {
      if ((stat.mode & 0o777) !== CARD_MODE) fs.chmodSync(file, CARD_MODE);
      return;
    }
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
  }
  const tmp = `${file}.tmp-${process.pid}-${crypto.randomUUID()}`;
  fs.writeFileSync(tmp, content, { mode: 0o600, flag: 'wx' });
  fs.chmodSync(tmp, CARD_MODE);
  fs.renameSync(tmp, file);
}

/**
 * Writes generated copies of the allowed cards into `<configDir>/agent` (a real dir,
 * never a link to the shared one) and removes anything else there.
 * @param {string} configDir the local `<XDG_CONFIG_HOME>/opencode`
 * @param {string} sourceDir the shared agent dir (read only)
 * @throws {LocalAgentCardsUnavailableError} when an allowed card is missing
 */
export function materializeLocalAgentCards(configDir, sourceDir) {
  const cards = LOCAL_TASK_AGENTS.map((agent) => {
    try {
      return [`${agent}.md`, localAgentCardContent(fs.readFileSync(path.join(sourceDir, `${agent}.md`), 'utf8'))];
    } catch {
      throw new LocalAgentCardsUnavailableError(`agent card missing: ${agent}`);
    }
  });
  const agentDir = path.join(configDir, 'agent');
  ensureRealAgentDir(agentDir);
  const wanted = new Set(cards.map(([name]) => name));
  for (const entry of fs.readdirSync(agentDir)) {
    if (!wanted.has(entry)) fs.rmSync(path.join(agentDir, entry), { recursive: true, force: true });
  }
  for (const [name, content] of cards) writeReadOnly(path.join(agentDir, name), content);
}
