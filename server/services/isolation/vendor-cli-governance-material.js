/**
 * vendor-cli-governance-material — the vendor-NEUTRAL governance materialization
 * primitive (SL-1, ADR-062). Generalizes the Codex-specific primitives of
 * codex-governance-material.js into filename/source-parametrized functions so a
 * single mechanism serves EVERY governed CLI provider (codex today; kimi and the
 * opencode carrier next) and any future one.
 *
 * SECURITY INVARIANT (inherited verbatim from the 2026-07-12 Codex remediation,
 * ADR-057 for the governance FILE specifically):
 *
 *   A full-access vendor turn (e.g. Codex danger-full-access) must NEVER be able to
 *   corrupt the shared, fleet-wide neutral governance source. So governance is
 *   materialized as a real, read-only (0444) per-user COPY — never a symlink. The
 *   worst a hostile/compromised turn can do is damage its OWN copy, which the next
 *   spawn's fail-closed guard detects by content fingerprint and rewrites; it can
 *   never reach the shared source (a same-uid full-access agent can chmod its own
 *   copy and overwrite it, but that is caught before the next turn and only ever
 *   affects that one user's next turn, never the fleet source).
 *
 * IDENTITY, not mere existence: "governed" means the copy is a real, non-empty file
 * whose sha256 EQUALS the neutral source's — not just "a file exists" (a subverted
 * or stale file would pass a size>0 check). Drift (source regenerated by
 * build-agents) or corruption both fail the identity check and trigger a rewrite.
 *
 * NEUTRALITY: this module hardcodes NO vendor filename and NO source path — the
 * caller supplies both. It has no vendor imports and no internal isolation imports,
 * so it stays the shared leaf primitive both the provisioning fast path and every
 * fail-closed spawn guard can depend on without a cycle.
 */

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

/**
 * Default read-only mode for a materialized governance copy. A same-uid agent can
 * still chmod+rewrite it, but 0444 stops accidental/naive writes and signals intent;
 * the hard guarantee is the per-turn fingerprint re-check + the copy (not link) itself.
 */
export const DEFAULT_GOVERNANCE_FILE_MODE = 0o444;

/** sha256 hex of a buffer or string. */
export function fingerprintOf(content) {
  return crypto.createHash('sha256').update(content).digest('hex');
}

/**
 * True iff `sourcePath` is a usable neutral source: a real, non-empty regular file
 * (following symlinks — the operator source is normally a link chain into the
 * governance repo). Cheaper than readNeutralSource for the "which source do we
 * use?" decision, which runs on every spawn; it stats instead of reading ~15KB.
 *
 * @param {string} sourcePath
 * @returns {boolean}
 */
export function hasUsableSource(sourcePath) {
  try {
    const st = fs.statSync(sourcePath);
    return st.isFile() && st.size > 0;
  } catch {
    return false;
  }
}

/**
 * Reads a neutral governance source file at `sourcePath` (following any symlink
 * chain — READS are safe, only writes-through are the risk).
 *
 * @param {string} sourcePath absolute path to the neutral source file
 * @returns {{ content: Buffer, fingerprint: string } | null} null when the source
 *   is absent or empty (cannot govern).
 */
export function readNeutralSource(sourcePath) {
  try {
    const content = fs.readFileSync(sourcePath);
    if (content.length === 0) {
      return null;
    }
    return { content, fingerprint: fingerprintOf(content) };
  } catch {
    return null;
  }
}

/**
 * True iff the file at `targetPath` is a real, non-empty regular file (NOT a
 * symlink) whose content fingerprint MATCHES the current neutral source at
 * `sourcePath` — i.e. authentic, current governance. A symlink, a missing/empty
 * file, or any drift (corrupted, stale, or subverted content) returns false so the
 * fail-closed guard repairs or blocks. When the source itself is unreadable this
 * returns false (governance cannot be attested).
 *
 * lstat (not stat) is deliberate: a symlink must NOT be accepted as governed — that
 * is the write-through corruption vector this module exists to close.
 *
 * @param {string} targetPath the per-user copy to verify
 * @param {string} sourcePath the neutral source to verify against
 * @returns {boolean}
 */
export function governanceMatchesSource(targetPath, sourcePath) {
  const src = readNeutralSource(sourcePath);
  if (!src) {
    return false;
  }
  try {
    const st = fs.lstatSync(targetPath);
    // lstat on a symlink reports isFile()===false, so this rejects links too.
    if (!st.isFile()) {
      return false;
    }
    const current = fs.readFileSync(targetPath);
    if (current.length === 0) {
      return false;
    }
    return fingerprintOf(current) === src.fingerprint;
  } catch {
    return false;
  }
}

/**
 * Materializes governance as a real, read-only COPY at <home>/<filename>,
 * (re)writing it whenever it is missing, a symlink, empty, or drifted from the
 * neutral source at `sourcePath`. A COPY — never a symlink — is the security
 * invariant (see module header). Never throws.
 *
 * @param {string} home the config-home dir whose <filename> to establish
 * @param {string} filename the governance filename the vendor CLI ingests
 * @param {string} sourcePath absolute path to the neutral source
 * @param {{ mode?: number, onError?: (err: unknown) => void }} [options]
 *   mode: file mode for the copy (default 0444).
 *   onError: invoked with the caught error on a write failure — lets the caller
 *     emit its own vendor-specific, fail-closed-vs-best-effort log. Not called on
 *     the "no source" path (that returns false without touching the filesystem).
 * @returns {boolean} whether governance matches the source after the attempt
 */
export function materializeGovernanceCopy(home, filename, sourcePath, options = {}) {
  const { mode = DEFAULT_GOVERNANCE_FILE_MODE, onError } = options;
  const targetPath = path.join(home, filename);
  if (governanceMatchesSource(targetPath, sourcePath)) {
    return true;
  }
  const src = readNeutralSource(sourcePath);
  if (!src) {
    // No neutral source on this node (build-agents output absent) — cannot govern;
    // the caller blocks the launch (fail-closed) or degrades (best-effort).
    return false;
  }
  try {
    fs.mkdirSync(home, { recursive: true });
    // Remove whatever is there first: a stale copy, a dangling/hostile symlink, or a
    // wrong-type entry. rmSync removes the directory ENTRY (needs write on home,
    // owned 0700 by us) — it does NOT follow a symlink to write the target, so the
    // shared source is never touched.
    fs.rmSync(targetPath, { force: true });
    // Write 0600 first (umask-safe, never a transient world-readable window) then
    // tighten to the requested read-only mode.
    fs.writeFileSync(targetPath, src.content, { mode: 0o600 });
    fs.chmodSync(targetPath, mode);
  } catch (err) {
    if (typeof onError === 'function') {
      onError(err);
    }
    return false;
  }
  return governanceMatchesSource(targetPath, sourcePath);
}
